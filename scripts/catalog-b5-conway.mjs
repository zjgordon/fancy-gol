/** Barber-pole family: bipole n=2, tripole n=3, … */
function barberPole(n) {
  const names = { 2: 'Bipole', 3: 'Tripole', 4: 'Quadpole', 5: 'Pentapole', 6: 'Hexapole', 7: 'Heptapole' };
  const pages = { 2: 'Bipole', 3: 'Tripole', 4: 'Quadpole', 5: 'Pentapole', 6: 'Hexapole', 7: 'Heptapole' };
  const w = 2 * n + 1;
  const h = 2 * n + 1;
  const rows = Array.from({ length: h }, () => '.'.repeat(w).split(''));
  for (let i = 0; i < n; i++) {
    const x = 2 * i;
    const y = 2 * i;
    rows[y][x] = 'o';
    rows[y][x + 1] = 'o';
    rows[y + 1][x] = 'o';
    if (i < n - 1) {
      rows[y + 1][x + 2] = 'o';
      rows[y + 2][x + 2] = 'o';
    } else {
      rows[y + 1][x + 1] = 'o';
    }
  }
  return {
    id: pages[n].toLowerCase(),
    name: names[n],
    author: 'unknown',
    year: 1970,
    ruleset: 'conway',
    category: 'oscillator',
    period: 2,
    grid: rows.map((r) => r.join('')).join('\n'),
    source: wiki(pages[n]),
    verified: 'period 2 barber-pole',
    tags: ['oscillator', 'conway', 'barber-pole'],
    description: [`A period-2 barber pole with ${n} twists. The classic rotor-on-a-diagonal.`],
  };
}

