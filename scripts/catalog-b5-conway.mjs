function longShip(n, id, name, page) {
  const rows = [];
  rows.push('oo' + '.'.repeat(n - 2));
  for (let i = 0; i < n - 2; i++) {
    rows.push('.' + 'o' + '.'.repeat(i) + 'o' + '.'.repeat(Math.max(0, n - 3 - i)));
  }
  rows.push('.'.repeat(n - 2) + 'oo');
  return {
    id,
    name,
    author: 'unknown',
    year: 1970,
    ruleset: 'conway',
    category: 'still-life',
    period: 1,
    grid: rows.join('\n'),
    source: wiki(page),
    verified: `period 1, long-ship family n=${n}`,
    tags: ['still-life', 'conway', 'ship-family'],
    description: [
      `A ship stretched to ${n} cells on the diagonal. Same closed hull, just more middle.`,
    ],
  };
}

